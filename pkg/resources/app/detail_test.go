func TestAppDetailDropsAutoGeneratedImage(t *testing.T) {
	// Compose-built image names like "current-web" have no tag or
	// registry path and duplicate the service name; the view should
	// hide them.
	view := appDetail(App{
		Name: "api",
		Envs: "dev",
		envStatuses: map[string][]lightsail.Status{
			"dev": {{
				Instance: "box-a",
				Status:   "healthy",
				Containers: []lightsail.ContainerStatus{
					{Name: "current-web-1", Service: "web", Image: "current-web", Status: "running"},
				},
			}},
		},
	})
	val := getRow(view, "  web")
	if val == "" {
		t.Fatal("expected service row for 'web'")
	}
	if strings.Contains(stripAnsi(val), "current-web") {
		t.Errorf("auto-generated image should be hidden; got %q", val)
	}
}

