func TestShowImage(t *testing.T) {
	cases := []struct {
		img  string
		want bool
	}{
		{"", false},
		{"current-web", false},      // auto-generated
		{"myapp-backend", false},    // auto-generated
		{"nginx:latest", true},      // tagged
		{"ghcr.io/owner/app", true}, // registry path
		{"docker.io/library/redis:7", true},
	}
	for _, tc := range cases {
		c := lightsail.ContainerStatus{Image: tc.img}
		if got := showImage(c); got != tc.want {
			t.Errorf("showImage(%q) = %v, want %v", tc.img, got, tc.want)
		}
	}
}

// --- helpers ---

func assertDetailRow(t *testing.T, view registry.DetailView, label, want string) {
	t.Helper()
	for _, section := range view.Sections {
		for _, row := range section.Rows {
			if row.Label == label {
				if got := stripAnsi(row.Value); got != want {
					t.Fatalf("%s = %q; want %q", label, got, want)
				}
				return
			}
		}
	}
	t.Fatalf("detail row %q not found in %+v", label, view)
}

// countSections reports how many sections have the given title. Used
// by regression tests that guard against the multi-instance duplication
// bug (two "Environment: dev" sections per env).
func countSections(view registry.DetailView, title string) int {
	n := 0
	for _, section := range view.Sections {
		if section.Title == title {
			n++
		}
	}
	return n
}

func getRow(view registry.DetailView, label string) string {
	for _, section := range view.Sections {
		for _, row := range section.Rows {
			if row.Label == label {
				return row.Value
			}
		}
	}
	return ""
}

func collectRows(view registry.DetailView, label string) []string {
	var out []string
	for _, section := range view.Sections {
		for _, row := range section.Rows {
			if row.Label == label {
				out = append(out, stripAnsi(row.Value))
			}
		}
	}
	return out
}

func contains(s []string, want string) bool {
	for _, v := range s {
		if v == want {
			return true
		}
	}
	return false
}

// stripAnsi removes CSI-SGR escape sequences so test assertions can
// match plain text regardless of whether lipgloss colorized the value.
// Mirrors the helper used in triad's tui tests.
func stripAnsi(s string) string {
	var b strings.Builder
	in := false
	for _, r := range s {
		if r == 0x1b {
			in = true
			continue
		}
		if in {
			if r == 'm' {
				in = false
			}
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}
